import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { DatabaseSync } from 'node:sqlite';
const root = 'E:/AI/projects/uoink/checkouts/Yoink-library';
const work = 'C:/Users/hello/AppData/Local/AgentControlRoom/worktrees/uoink-library/31e8890c-ab8/gemini';
const runId = '31e8890c-ab80-44d0-8062-3347942bc6cf';
const out = path.join(root, '_scratch/interrupted-retirement-root-provenance01');
if (fs.existsSync(out)) throw new Error('fresh output required');
fs.mkdirSync(out);
const write = (n,v) => fs.writeFileSync(path.join(out,n), JSON.stringify(v,null,2)+'\n',{flag:'wx'});
const sha = b => crypto.createHash('sha256').update(b).digest('hex');
const mapPath = 'docs/library/proof/interrupted-owner-retirement-direction-2026-09-13/corrected/INPUTS.json';
const map = JSON.parse(fs.readFileSync(path.join(root,mapPath),'utf8'));
const sources = map.inputs.map(i => {
  if (!i.path.startsWith('docs/library/proof/') || i.path.includes('..') || !i.path.endsWith('.py')) throw new Error('fixed text boundary');
  const a = fs.readFileSync(path.join(root,i.path));
  const b = fs.readFileSync(path.join(work,i.path));
  if (a.length !== i.bytes || sha(a) !== i.sha256 || !a.equals(b)) throw new Error('source binding '+i.id);
  return {...i, roots_match:true};
});
const dir = path.join(work,'_scratch/interrupted-owned-session-retirement-implementation01');
const outputs = fs.readdirSync(dir,{withFileTypes:true}).map(e => {
  if(!e.isFile() || !/\.(py|patch|md|json)$/.test(e.name)) throw new Error('unexpected output');
  const b=fs.readFileSync(path.join(dir,e.name));
  return {path:e.name,bytes:b.length,sha256:sha(b)};
});
write('SOURCE-BINDINGS.json',{map_sha256:sha(fs.readFileSync(path.join(root,mapPath))),sources,outputs});
const db=new DatabaseSync('C:/Users/hello/AppData/Local/AgentControlRoom/control-room.sqlite',{readOnly:true});
const run=db.prepare('SELECT id, status, started_at, finished_at, summary FROM runs WHERE id=?').get(runId);
const workers=db.prepare('SELECT id,agent,model,phase,status,session_id,worktree_path,output,error,started_at,finished_at FROM agent_runs WHERE run_id=?').all(runId);
const events=db.prepare('SELECT id,agent,type,message,payload_json,created_at FROM events WHERE run_id=? ORDER BY id').all(runId);
db.close();
write('CONTROL-ROOM-RUN.json',{run,workers});
write('CONTROL-ROOM-EVENTS.json',events);
const toolEvents=events.filter(e=>e.type==='tool').map(e=>({id:e.id,message:e.message,payload:e.payload_json?JSON.parse(e.payload_json):null}));
write('TOOL-EVENTS.json',toolEvents);
const commands=toolEvents.filter(e=>e.message.includes('run_command'));
write('COMMAND-EVENTS.json',commands);
console.log(JSON.stringify({run_status:run.status,workers:workers.map(w=>({agent:w.agent,model:w.model,status:w.status,error:w.error})),source_count:sources.length,source_bytes:sources.reduce((s,x)=>s+x.bytes,0),outputs,events:events.length,tool_events:toolEvents.length,commands},null,2));
