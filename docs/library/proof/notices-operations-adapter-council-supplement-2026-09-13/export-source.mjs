import { DatabaseSync } from 'node:sqlite';
import { writeFileSync } from 'node:fs';
const runId = 'ca1e1356-b943-4a8a-bee4-6a3016a7ee64';
const db = new DatabaseSync('C:/Users/hello/AppData/Local/AgentControlRoom/control-room.sqlite', { readOnly: true });
const run = db.prepare('SELECT id, status, started_at, finished_at FROM runs WHERE id = ?').get(runId);
const workers = db.prepare('SELECT id, agent, model, status, worktree_path, error, started_at, finished_at FROM agent_runs WHERE run_id = ?').all(runId);
const tools = db.prepare("SELECT id, agent_run_id, agent, type, message, payload_json, created_at FROM events WHERE run_id = ? AND type = 'tool' ORDER BY id").all(runId);
db.close();
if (run?.status !== 'completed' || workers.length !== 1 || workers[0].status !== 'completed') throw new Error('Review not completed');
const output = { scope: 'Read-only Control Room source-access event metadata; not an OS audit or complete displayed-source record', run, workers, tools };
writeFileSync('_scratch/COUNCIL-SUPPLEMENT01-SOURCE-OBSERVATIONS.json', JSON.stringify(output, null, 2) + '\n', { flag: 'wx' });
