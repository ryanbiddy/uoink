    if ((Get-FileHash -LiteralPath $taskCopy -Algorithm SHA256).Hash.ToLowerInvariant() -ne $taskHash) { throw 'Input copy mismatch' }
    $taskRecords += [ordered]@{name=$taskName;source=$taskOriginal;sha256=$taskHash}
}
